import streamlit as st
import joblib
import pandas as pd

model = joblib.load("churn_model.pkl")
preprocessor = joblib.load("churn_preprocessor.pkl")

# Sidebar
with st.sidebar:
    st.header("About the Project")

    st.write(
        "This application predicts whether a telecom customer "
        "is likely to churn based on customer, service, contract, "
        "and billing information."
    )

    st.subheader("Model")
    st.write("Logistic Regression")

    st.subheader("Model Performance")
    st.write("Accuracy: 80.55%")
    st.write("Precision: 65.72%")
    st.write("Recall: 55.88%")
    st.write("F1 Score: 60.40%")

st.title("📊 Customer Churn Prediction")
st.write(
    "Enter the customer's information below to predict"
    "the likelihood of customer churn."
)
st.info(
    "The model uses customers demographic,service,contract,"
    "and billinf information to generate a churn prediction."
)

st.caption(
    "⚠️ This prediction is generated by a machine-learning model "
    "and should be used as an analytical estimate, not a guarantee."
)

with st.expander("ℹ️ How to use this app"):
    st.write(
        "1. Enter the customer's information using the fields below."
    )
    st.write(
        "2. Click the 'Predict Churn' button."
    )
    st.write(
        "3. The model will predict whether the customer is likely "
        "to churn."
    )
    st.write(
        "4. The app will also display the estimated churn probability."
    )

st.subheader("👤 Customer Information")

gender = st.selectbox(
    "Gender",
    ["Female", "Male"]
)

senior_citizen = st.selectbox(
    "Senior Citizen",
    ["No", "Yes"]
)

partner = st.selectbox(
    "Partner",
    ["No", "Yes"]
)

dependents = st.selectbox(
    "Dependents",
    ["No", "Yes"]
)

tenure = st.number_input(
    "Tenure (months)",
    min_value=0,
    max_value=72,
    value=12
)

st.subheader("📱 Services")

phone_service = st.selectbox(
    "Phone Service",
    ["No", "Yes"]
)

multiple_lines = st.selectbox(
    "Multiple Lines",
    ["No", "Yes", "No phone service"]
)

internet_service = st.selectbox(
    "Internet Service",
    ["DSL", "Fiber optic", "No"]
)

online_security = st.selectbox(
    "Online Security",
    ["No", "Yes", "No internet service"]
)

online_backup = st.selectbox(
    "Online Backup",
    ["No", "Yes", "No internet service"]
)

device_protection = st.selectbox(
    "Device Protection",
    ["No", "Yes", "No internet service"]
)

tech_support = st.selectbox(
    "Tech Support",
    ["No", "Yes", "No internet service"]
)

streaming_tv = st.selectbox(
    "Streaming TV",
    ["No", "Yes", "No internet service"]
)

streaming_movies = st.selectbox(
    "Streaming Movies",
    ["No", "Yes", "No internet service"]
)

st.subheader("📄 Contract & Billing")

contract = st.selectbox(
    "Contract",
    ["Month-to-month", "One year", "Two year"]
)

paperless_billing = st.selectbox(
    "Paperless Billing",
    ["No", "Yes"]
)

payment_method = st.selectbox(
    "Payment Method",
    [
        "Electronic check",
        "Mailed check",
        "Bank transfer (automatic)",
        "Credit card (automatic)"
    ]
)

st.subheader("💰 Charges")

monthly_charges = st.number_input(
    "Monthly Charges",
    min_value=18.25,
    max_value=118.75,
    value=64.76
)

total_charges = st.number_input(
    "Total Charges",
    min_value=0.0,
    value=1000.0
)

#prediction

# Prediction
if st.button("Predict Churn"):

    senior_citizen_value = 1 if senior_citizen == "Yes" else 0

    customer_data = pd.DataFrame({
        "gender": [gender],
        "SeniorCitizen": [senior_citizen_value],
        "Partner": [partner],
        "Dependents": [dependents],
        "tenure": [tenure],
        "PhoneService": [phone_service],
        "MultipleLines": [multiple_lines],
        "InternetService": [internet_service],
        "OnlineSecurity": [online_security],
        "OnlineBackup": [online_backup],
        "DeviceProtection": [device_protection],
        "TechSupport": [tech_support],
        "StreamingTV": [streaming_tv],
        "StreamingMovies": [streaming_movies],
        "Contract": [contract],
        "PaperlessBilling": [paperless_billing],
        "PaymentMethod": [payment_method],
        "MonthlyCharges": [monthly_charges],
        "TotalCharges": [total_charges]
    })

    processed_data = preprocessor.transform(customer_data)

    prediction = model.predict(processed_data)

    probability = float(
        model.predict_proba(processed_data)[0][1]
    )

    if prediction[0] == "Yes":
        st.error("⚠️ Customer is likely to churn")
    else:
        st.success("✅ Customer is unlikely to churn")

    st.metric(
        label="Churn Probability",
        value=f"{probability:.2%}"
    )

    if probability < 0.30:
        st.write("🟢 Low estimated churn probability.")
    elif probability < 0.60:
        st.write("🟡 Moderate estimated churn probability.")
    else:
        st.write("🔴 High estimated churn probability.")